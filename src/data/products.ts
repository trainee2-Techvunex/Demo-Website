const byId = new Map(PRODUCTS.map((p) => [p.id, p]));
const bySlug = new Map(PRODUCTS.map((p) => [p.slug, p]));

export function getProduct(idOrSlug: string): Product | null {
  return byId.get(idOrSlug) ?? bySlug.get(idOrSlug) ?? null;
}

export function getBrandsForCategory(category?: string | null): string[] {
  const list = category ? PRODUCTS.filter((p) => p.category === category) : PRODUCTS;
  return Array.from(new Set(list.map((p) => p.brand))).sort();
}
